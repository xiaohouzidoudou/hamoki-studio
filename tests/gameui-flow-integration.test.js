'use strict';
const test=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),net=require('node:net');
const {spawn}=require('node:child_process');
const ROOT=path.join(__dirname,'..');
const urlPort=()=>new Promise((resolve,reject)=>{const s=net.createServer();s.once('error',reject);s.listen(0,'127.0.0.1',()=>{const port=s.address().port;s.close(()=>resolve(port));});});
async function waitFor(url,child){for(let i=0;i<75;i++){if(child.exitCode!==null)throw Error('Server exited with '+child.exitCode);try{const r=await fetch(url+'/api/status');if(r.ok)return;}catch{}await new Promise(r=>setTimeout(r,80));}throw Error('QA server did not start');}
test('game UI workflow remains real and version-linked in isolated demo server',{timeout:45000},async t=>{
 const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'hamoki-gameui-flow-')),port=await urlPort(),host='http://127.0.0.1:'+port;
 const child=spawn(process.execPath,['server.js'],{cwd:ROOT,env:{...process.env,HOST:'127.0.0.1',PORT:String(port),DATA_DIR:tmp,DEMO_MODE:'1',APP_PASSWORD:'gameui-test-only'},stdio:'ignore',windowsHide:true});
 t.after(()=>{child.kill();fs.rmSync(tmp,{recursive:true,force:true,maxRetries:5,retryDelay:100});});
 await waitFor(host,child);
 const get=async path=>{const r=await fetch(host+path);assert.equal(r.status,200,path);return r;};
 const json=async(path,method,body,expected=200)=>{const r=await fetch(host+path,{method,headers:{'Content-Type':'application/json'},body:JSON.stringify(body)});const data=await r.json();assert.equal(r.status,expected,JSON.stringify(data));return data;};
 for(const resource of ['/','/studio-v4.css','/gameui-flow.html','/flow-entry.css','/flow-entry.js','/gameui-flow.css','/gameui-flow.js','/gameui-flow-tools.js','/assets/hamoki-clipboard.js'])await get(resource);
 const home=await (await get('/')).text();assert.match(home,/data-view="game-ui-flow"/);
 assert.match(home,/data-view="image-generate"/,'text and image generation share one module');
 assert.doesNotMatch(home,/data-view="text2img"|data-view="img2img"/,'do not create duplicate modes');
 assert.match(home,/studio-v4\.css/);
 const flowResponse=await get('/gameui-flow.html');
 assert.match(flowResponse.headers.get('content-security-policy')||'',/frame-ancestors 'self'/,'workflow iframe must be allowed on the same origin');
 const flow=await flowResponse.text();assert.match(flow,/gameui-flow-tools\.js/);
 assert.doesNotMatch(flow,/data-tool="link"/,'manual linking is not exposed');
 const flowStyle=await(await get('/gameui-flow.css')).text();
 assert.match(flowStyle,/\.edge-layer\{[^}]*width:6000px;height:4000px/,'SVG connectors must not inherit global 18px icon size');
 const providers=(await (await get('/api/providers')).json()).providers;assert.ok(providers.length>0);
 const projects=await (await get('/api/projects')).json();const id=projects.defaultId;assert.ok(id);
 const base64=fs.readFileSync(path.join(ROOT,'assets','hamoki-avatar-128.png')).toString('base64');
 const image='data:image/png;base64,'+base64;
 const a=(await json('/api/projects/'+id+'/assets','POST',{image,name:'主界面',x:140,y:100},201)).node;
 const b=(await json('/api/projects/'+id+'/assets','POST',{image,name:'拆件 · 主按钮',x:520,y:120,parentNodeId:a.id},201)).node;
 assert.equal(b.parentNodeId,a.id,'child auto-links to source');
 const cropped=(await json('/api/projects/'+id+'/assets','POST',{image,name:'裁切',parentNodeId:a.id,placement:'related',w:288,h:288},201)).node;
 assert.equal(cropped.parentNodeId,a.id,'crop keeps its original source');
 assert.equal(cropped.x,a.x,'crop stays aligned vertically with source');
 assert.equal(cropped.y,a.y+a.h+52,'first derived image appears below source');
 const transparent=(await json('/api/projects/'+id+'/assets','POST',{image,name:'透明背景',parentNodeId:a.id,placement:'related',w:288,h:288},201)).node;
 assert.equal(transparent.parentNodeId,a.id,'transparent result keeps its source');
 assert.equal(transparent.x,a.x);
 assert.equal(transparent.y,a.y-288-52,'second related image chooses free space above');
 const copied=(await json('/api/projects/'+id+'/nodes/duplicate','POST',{sourceNodeId:a.id,x:190,y:157,w:290,h:286},201)).node;
 assert.notEqual(copied.id,a.id,'paste must have an independent node id');
 assert.equal(copied.assetFile,a.assetFile,'pasted node shares the original full-resolution media file');
 assert.equal(copied.x,190);assert.equal(copied.y,157);
 assert.equal(copied.parentNodeId,null,'copying must not invent an AI lineage edge');
 const missing=await json('/api/projects/'+id+'/nodes/duplicate','POST',{sourceNodeId:'00000000-0000-0000-0000-000000000000'},404);
 assert.match(missing.error,/不存在/);
 const invalid=await json('/api/projects/'+id+'/nodes/'+a.id,'PATCH',{parentNodeId:b.id},400);
 assert.match(invalid.error,/循环/);
 const detached=await json('/api/projects/'+id+'/nodes/'+b.id,'PATCH',{parentNodeId:null});
 assert.equal(detached.node.parentNodeId,null);
 const linked=await json('/api/projects/'+id+'/nodes/'+b.id,'PATCH',{parentNodeId:a.id});
 assert.equal(linked.node.parentNodeId,a.id);
 const submitted=await json('/api/jobs','POST',{projectId:id,sourceNodeId:a.id,prompt:'生成同风格游戏UI版本',referenceNodes:[{nodeId:a.id,role:'general'}],targets:[{providerId:providers[0].id,model:providers[0].imageModel}],ratio:'16:9',resolution:'1K',quality:'auto',count:1,editMode:'new'},201);
 assert.equal(submitted.jobs.length,1);
 let job=null;for(let i=0;i<75;i++){const jobs=(await(await get('/api/jobs?projectId='+id)).json()).jobs;job=jobs.find(j=>j.id===submitted.jobs[0].id);if(job?.status==='done'||job?.status==='failed')break;await new Promise(r=>setTimeout(r,80));}
 assert.equal(job.status,'done',job.error||'should generate a demo child');
 const project=(await (await get('/api/projects/'+id)).json()).project;
 assert.ok(project.nodes.some(n=>n.kind==='generated'&&n.parentNodeId===a.id),'real API persists child relationship');
 assert.ok(project.nodes.some(n=>n.id===b.id&&n.parentNodeId===a.id),'manual relationship survives');
 const generated=project.nodes.find(n=>n.kind==='generated'&&n.parentNodeId===a.id);
 const generatedCopy=(await json('/api/projects/'+id+'/nodes/duplicate','POST',{sourceNodeId:generated.id},201)).node;
 assert.equal(generatedCopy.kind,'reference','copy of a generated image is a reusable image asset');
 const generatedHistory=(await(await get('/api/history?projectId='+id)).json()).history;
 assert.ok(generatedHistory.some(h=>h.file===generatedCopy.assetFile),'copy of generated media preserves exact image bytes');
});
